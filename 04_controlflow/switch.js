const month = 12

switch(month){
    case 1:
        console.log("january");
        break;
    case 2:
        console.log("february");
        break;
    case 3:
        console.log("march");
        break;
    case 4:
        console.log("April");
        break;
    case 5:
        console.log("May");
        break;
    case 6:
        console.log("june");
        break;
    case 7:
        console.log("july");
        break;
    case 8:
        console.log("August");
        break;
    case 9:
        console.log("Septemember");
        break;
    case 10:
        console.log("October");
        break;
    case 11:
        console.log("November");
        break;
    case 9:
        console.log("December");
        break;
    default:
        console.log("MONTH NOT MATCH");
        
}

const day = "sss"

switch(day){
    case "sun":
        console.log("Today is sunday");
        break;
    case "mon":
        console.log("Today is monday");
        break;
    case "tues":
        console.log("Today is Tuesday");
        break;
    default:
        console.log("Not a valid day");
        

}
